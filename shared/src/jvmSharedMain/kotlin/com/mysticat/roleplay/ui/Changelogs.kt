package com.mysticat.roleplay.ui

/**
 * 应用内更新日志：**只保留当前版本**，历史版本走
 * [AppLinks.CHANGELOG_DOC_URL] 的飞书文档，避免应用内越积越长。
 *
 * 为什么两端各一份常量：两个平台**版本号独立编**（Android 与桌面各走各的版本线），
 * 各自发的版、各自记的账；且桌面首版的内容里有"桌面特有"的条目（便携包替换、系统朗读走
 * Windows 语音等），混在一份里会误导用户。运行时按 [Platform.ui] 的 `platformId` 取其一。
 *
 * 更新方式：发版时改写对应那份（桌面发版改 [DESKTOP]，Android 发版改 [ANDROID]）。
 */
internal object Changelogs {

    /** Android 当前版本的内置更新日志（对外日志的精简版，`· ` 前缀） */
    const val ANDROID = """0.3.1-alpha.2（2026-10-15）
· 意见反馈拆成两条路：「关于鲸鱼 → 意见反馈」可选 GitHub 表单或飞书匿名表单
· 投稿被采用上架后可以撤回了（不再需要重投一遍）
· 修复：发现页换了封面仍显示旧图（清单带上内容指纹，换图即刷新）
· 发现页顶部统计收成「N 组 · M 卡」，不再是一长串枚举
· 旁白不再要求模型加标记：上版那条「用 > 起头」实测拿不到，已撤掉，旁白按普通正文显示
· 修复：投稿单里附的文件下载不下来"""

    /** Windows 桌面版当前版本的内置更新日志（发版时替换成对外日志的精简版） */
    const val DESKTOP = """1.8.1（2026-10-15）· 功能对齐 Android 0.3.1-alpha.2
· Esc 只关最上面一层：右键菜单或弹窗开着时按 Esc 不再连带退出底下的会话 / 页面
· 意见反馈拆成两条路：「关于鲸鱼 → 意见反馈」可选 GitHub 表单或飞书匿名表单
· 投稿被采用上架后可以撤回了（不再需要重投一遍）
· 修复：发现页换了封面仍显示旧图（清单带上内容指纹，换图即刷新）
· 发现页顶部统计收成「N 组 · M 卡」；「编辑世界书」页头与其余内嵌页统一
· 旁白不再要求模型加标记：上版那条「用 > 起头」实测拿不到，已撤掉，旁白按普通正文显示"""


    /** 按平台取当前版本的日志文本 */
    val current: String
        get() = if (com.mysticat.roleplay.ui.Platform.ui.platformId() == "desktop") DESKTOP else ANDROID
}
