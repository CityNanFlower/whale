package com.mysticat.roleplay.ui

/**
 * 应用内更新日志：**只保留当前版本**，历史版本走
 * [AppLinks.CHANGELOG_DOC_URL] 的金山文档，避免应用内越积越长。
 *
 * 为什么两端各一份常量：两个平台**版本号独立编**（Android 与桌面各走各的版本线），
 * 各自发的版、各自记的账；且桌面首版的内容里有"桌面特有"的条目（便携包替换、系统朗读走
 * Windows 语音等），混在一份里会误导用户。运行时按 [Platform.ui] 的 `platformId` 取其一。
 *
 * 更新方式：发版时改写对应那份（桌面发版改 [DESKTOP]，Android 发版改 [ANDROID]）。
 */
internal object Changelogs {

    /** Android 当前版本的内置更新日志（对外日志的精简版，`· ` 前缀） */
    const val ANDROID = """0.3.0-alpha.2（2026-10-12）
· 语音页「试识别」补到系统识别引擎（此前需接入识别供应商才可见），识别中可停止收音
· 聊天背景按图自动适配主题：按深浅色做像素级明暗归一，与电脑端同一观感
· 通知类弹窗统一形式：发现页 / 宝库导入结果与错误提示改底部浮层
· 灵感模板、新建分类、添加角色卡链接、皮肤投稿等输入框统一行表式样式"""

    /** Windows 桌面版当前版本的内置更新日志（发版时替换成对外日志的精简版） */
    const val DESKTOP = """1.7.1（2026-10-12）· 功能对齐 Android 0.3.0-alpha.2
· 快捷键体系：用户页新增「快捷键」整页，全局 9 条＋输入框 3 条键位可改键 / 重置 / 恢复默认，新增切页 Ctrl+1~5
· Ctrl+B 冲突消除：输入框聚焦时让位给插入「」，全局收展侧栏其余时刻照常
· 「叙事设置」改占主栏＋右栏两段式（与编辑角色卡同版式），Esc 退出
· 素材库选择器改居中卡片；通知类弹窗与多处输入框形式统一
· 聊天背景按图自动适配主题（与手机端同一份归一）
· 修复安装版更改数据目录后「重启以生效」确认不出现的问题"""


    /** 按平台取当前版本的日志文本 */
    val current: String
        get() = if (com.mysticat.roleplay.ui.Platform.ui.platformId() == "desktop") DESKTOP else ANDROID
}
